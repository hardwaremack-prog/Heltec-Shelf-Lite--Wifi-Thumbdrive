#!/usr/bin/env python3
"""Pack web/index.html (gzipped) and the app icon into HeltecShelfLite/web_assets.h"""
import gzip, pathlib, io
from PIL import Image, ImageDraw

root = pathlib.Path(__file__).resolve().parent.parent

def make_icon(size=180):
    s = size / 180
    im = Image.new("RGB", (size, size), (22, 19, 15))
    d = ImageDraw.Draw(im)
    wood = (232, 163, 61); dark = (201, 119, 43)
    books = [(30, 22, 58, (127, 191, 127)), (54, 18, 64, (228, 106, 90)), (78, 26, 54, (243, 235, 223)),
             (110, 20, 60, (106, 160, 220)), (134, 24, 50, (232, 163, 61))]
    for x, w, h, c in books:   # top shelf
        d.rounded_rectangle([x*s, (78-h)*s, (x+w-4)*s, 78*s], radius=3*s, fill=c)
    d.rounded_rectangle([20*s, 78*s, 160*s, 88*s], radius=4*s, fill=wood)
    # bottom shelf: a music note and a folder
    d.rounded_rectangle([36*s, 112*s, 84*s, 146*s], radius=5*s, fill=dark)
    d.rounded_rectangle([36*s, 106*s, 58*s, 116*s], radius=3*s, fill=dark)
    d.ellipse([104*s, 128*s, 122*s, 146*s], fill=(243, 235, 223))
    d.rectangle([118*s, 102*s, 123*s, 137*s], fill=(243, 235, 223))
    d.polygon([(123*s, 102*s), (142*s, 110*s), (123*s, 116*s)], fill=(243, 235, 223))
    d.rounded_rectangle([20*s, 146*s, 160*s, 156*s], radius=4*s, fill=wood)
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    (root / "docs").mkdir(exist_ok=True)
    im.save(root / "docs" / "icon.png")
    return buf.getvalue()

def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i+20]) for i in range(0, len(data), 20)]
    return (f"static const size_t {name}_LEN = {len(data)};\n"
            f"static const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n")

html = (root / "web" / "index.html").read_bytes()
gz = gzip.compress(html, 9, mtime=0)
icon = make_icon()
out = ("// Generated by tools/build_web.py - edit web/index.html instead\n#pragma once\n#include <Arduino.h>\n"
       + c_array("INDEX_HTML_GZ", gz) + c_array("ICON_PNG", icon))
(root / "HeltecShelfLite" / "web_assets.h").write_text(out)
print(f"index.html {len(html)} -> {len(gz)} bytes gz, icon {len(icon)} bytes")
